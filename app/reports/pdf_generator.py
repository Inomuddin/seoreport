"""
app/reports/pdf_generator.py — PDF report generator using ReportLab.

ReportLab works on all platforms with no system dependencies.

Usage:
    from app.reports.pdf_generator import generate_pdf, save_pdf
    pdf_bytes = generate_pdf(report=report, user=user)
"""

