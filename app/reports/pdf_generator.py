# ── Colour helpers ─────────────────────────────────────────────────────────────

def _hex(hex_str: str) -> HexColor:
    """Convert a CSS hex colour string to a ReportLab HexColor."""
    hex_str = hex_str.strip()
    if not hex_str.startswith("#"):
        hex_str = "#" + hex_str
    try:
        return HexColor(hex_str)
    except Exception:
        return HexColor("#4F46E5")


COLOR_GREEN  = HexColor("#10b981")
COLOR_YELLOW = HexColor("#f59e0b")
COLOR_RED    = HexColor("#ef4444")
COLOR_GRAY   = HexColor("#6b7280")
COLOR_LIGHT  = HexColor("#f3f4f6")
COLOR_WHITE  = colors.white
COLOR_BLACK  = HexColor("#1f2937")


def _score_color(score: Optional[int]) -> HexColor:
    if score is None:
        return COLOR_GRAY
    if score >= 80:
        return COLOR_GREEN
    if score >= 50:
        return COLOR_YELLOW
    return COLOR_RED


def _status_color(status: str) -> HexColor:
    return {"pass": COLOR_GREEN, "warning": COLOR_YELLOW, "fail": COLOR_RED}.get(
        status, COLOR_GRAY
    )


def _status_icon(status: str) -> str:
    return {"pass": "PASS", "warning": "WARN", "fail": "FAIL"}.get(status, "—")


# ── Public API ─────────────────────────────────────────────────────────────────

def generate_pdf(report, user) -> bytes:
    """
    Render the SEO report as a PDF and return raw bytes.

    Args:
        report: Report model instance (must have .items and .client loaded).
        user:   User model instance (for brand colour).

    Returns:
        PDF file contents as bytes.
    """
    buffer = BytesIO()
    brand = _hex(user.brand_color or "#4F46E5")

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
        title=f"SEO Report — {report.client.name}",
        author=user.agency_name or user.full_name,
    )

    story = []
    styles = _build_styles(brand)

    # ── Cover ──────────────────────────────────────────────────────────────
    story += _build_cover(report, user, brand, styles)
    story.append(Spacer(1, 6 * mm))

    # ── Score summary ──────────────────────────────────────────────────────
    story += _build_scores(report, brand, styles)
    story.append(Spacer(1, 6 * mm))

    # ── Quick facts table ──────────────────────────────────────────────────
    story += _build_facts(report, brand, styles)
    story.append(Spacer(1, 6 * mm))

    # ── Checks by category ─────────────────────────────────────────────────
    categories = [
        ("performance", "Performance"),
        ("seo",         "On-Page SEO"),
        ("technical",   "Technical"),
        ("content",     "Content"),
    ]
    groups = _group_checks(report)
    for key, label in categories:
        items = groups.get(key, [])
        if items:
            story += _build_category(label, items, brand, styles)
            story.append(Spacer(1, 4 * mm))

    # ── Footer note ────────────────────────────────────────────────────────
    story.append(HRFlowable(width="100%", thickness=0.5, color=COLOR_LIGHT))
    story.append(Spacer(1, 2 * mm))
    agency = user.agency_name or user.full_name
    date_str = report.created_at.strftime("%Y-%m-%d")
    story.append(Paragraph(
        f"Generated by {agency} · {date_str} · SEO Report",
        styles["footer"],
    ))

    doc.build(story)
    return buffer.getvalue()


def save_pdf(report, user) -> str:
    """Generate PDF, save to disk, and return the filename."""
    pdf_bytes = generate_pdf(report, user)
    filename = f"report_{report.id}_{report.client_id}.pdf"
    upload_dir = _ensure_upload_dir()
    with open(os.path.join(upload_dir, filename), "wb") as f:
        f.write(pdf_bytes)
    return filename


def get_pdf_path(filename: str) -> str:
    """Return the absolute filesystem path for a stored PDF."""
    return os.path.join(_ensure_upload_dir(), filename)


# ── Internal builders ──────────────────────────────────────────────────────────

def _ensure_upload_dir() -> str:
    # Use REPORT_FOLDER from config if set; fall back to static/reports.
    upload_dir = current_app.config.get(
        "REPORT_FOLDER",
        os.path.join(current_app.static_folder, "reports"),
    )
    os.makedirs(upload_dir, exist_ok=True)
    return upload_dir


def _group_checks(report) -> dict:
    groups: dict = {}
    for item in report.items.all():
        groups.setdefault(item.category, []).append(item)
    return groups


